    def generate_case_bundle(
        self,
        case_id: str,
        *,
        dest_path: Path | None = None,
        options: ReportOptions | None = None,
    ) -> CaseBundleResult:
        """Create a verifiable offline .zip bundle with PDF, JSON, sidecars & MANIFEST.sha256.

        Never includes the raw SQLite database or any lock passphrase hashes.
        """
        case = self.cases.get_required(case_id)
        opts = options or ReportOptions()
        if dest_path is None:
            target = self._unique_default_path(case.id, None, "zip")
        else:
            target = Path(dest_path)
            if target.suffix.lower() != ".zip":
                target = target.with_suffix(".zip")
        self._check_export_storage(target)

        payload_json = self.build_payload(case.id, options=opts, include_reportlab_tool=False)
        payload_pdf = self.build_payload(case.id, options=opts, include_reportlab_tool=True)
        problems = validate_report_payload(payload_pdf)
        if problems:
            raise ReportValidationError("Report validation failed: " + "; ".join(problems))

        temp_parent = self.data_root / "temp"
        temp_parent.mkdir(parents=True, exist_ok=True)
        partial = target.with_name(target.name + ".partial")
        manifest_rows: list[tuple[str, str]] = []
        try:
            with tempfile.TemporaryDirectory(prefix="bundle-", dir=temp_parent) as stg:
                stg_path = Path(stg)
                json_file = stg_path / f"{case.id}-report.json"
                pdf_file = stg_path / f"{case.id}-report.pdf"
                json_file.write_bytes(
                    (json.dumps(payload_json, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
                )
                vis_assets: dict[str, dict[str, bytes]] = {}
                if opts.include_visuals:
                    for ev_entry in payload_pdf["evidence"]:
                        ev_obj = self.evidence.get(ev_entry["id"])
                        if ev_obj is None:
                            continue
                        asset: dict[str, bytes] = {}
                        tp = self.evidence.thumbnail_path(ev_obj)
                        if tp is not None and tp.is_file():
                            asset["main"] = tp.read_bytes()
                        if ((ev_entry.get("origin_trace") or {}).get("thumbnail_check") or {}).get(
                            "status"
                        ) == "mismatch":
                            etb = extract_embedded_thumbnail_bytes(
                                self.evidence.original_path(ev_obj)
                            )
                            if etb:
                                asset["exif_thumb"] = etb
                        if asset:
                            vis_assets[ev_obj.id] = asset
                render_pdf_report(payload_pdf, pdf_file, visual_assets=vis_assets or None)

                files_to_pack: list[tuple[str, Path]] = [
                    (f"reports/{json_file.name}", json_file),
                    (f"reports/{pdf_file.name}", pdf_file),
                ]
                c_dir = case_dir(self.data_root / "cases", case.id)
                meta_dir = c_dir / "metadata"
                if meta_dir.is_dir():
                    for mf in sorted(meta_dir.glob("*.json")):
                        if mf.is_file():
                            files_to_pack.append((f"metadata/{mf.name}", mf))
                der_dir = c_dir / "derived"
                if der_dir.is_dir():
                    for df in sorted(der_dir.glob("*-thumb.png")):
                        if df.is_file():
                            files_to_pack.append((f"thumbnails/{df.name}", df))

                with zipfile.ZipFile(partial, "w", compression=zipfile.ZIP_DEFLATED) as zf:
                    for arc_name, src_p in files_to_pack:
                        zf.write(src_p, arcname=arc_name)
                        manifest_rows.append((sha256_file(src_p), arc_name))
                    manifest_txt = "\n".join(f"{h}  {arc}" for h, arc in manifest_rows) + "\n"
                    zf.writestr("MANIFEST.sha256", manifest_txt.encode("utf-8"))
                # Verify archive integrity before atomic publish
                with zipfile.ZipFile(partial, "r") as zf:
                    if zf.testzip() is not None:
                        raise ReportError("Generated ZIP bundle failed CRC verification.")
            os.replace(partial, target)
        except BaseException:
            partial.unlink(missing_ok=True)
            raise

        digest = sha256_file(target)
        target.with_name(target.name + ".sha256").write_text(
            f"{digest}  {target.name}\n", encoding="utf-8"
        )
        author = (self.actor() or "Analyst").strip() or "Analyst"
        with self.db.transaction() as con:
            append_event(
                con,
                "case_bundle_exported",
                case_id=case.id,
                actor_label=author,
                details={
                    "filename": target.name,
                    "sha256": digest,
                    "file_count": len(manifest_rows) + 1,
                },
            )
        return CaseBundleResult(
            path=target,
            filename=target.name,
            sha256=digest,
            file_count=len(manifest_rows) + 1,
            manifest_entries=tuple(manifest_rows),
        )

    def get(self, export_id: int) -> ExportRecord | None:
        row = self.db.con.execute(
            "SELECT * FROM exports WHERE id = ?", (int(export_id),)
        ).fetchone()
        return ExportRecord.from_row(row) if row else None

    def get_required(self, export_id: int) -> ExportRecord:
        rec = self.get(export_id)
        if rec is None:
            raise ExportNotFoundError(f"Export record not found: {export_id}")
        return rec

    def list_exports(self, case_id: str, *, evidence_id: str | None = None) -> list[ExportRecord]:
        if evidence_id is not None:
            rows = self.db.con.execute(
                "SELECT * FROM exports WHERE case_id = ? AND "
                "(evidence_id = ? OR evidence_id IS NULL) ORDER BY id DESC",
                (case_id, evidence_id),
            )
        else:
            rows = self.db.con.execute(
                "SELECT * FROM exports WHERE case_id = ? ORDER BY id DESC", (case_id,)
            )
        return [ExportRecord.from_row(r) for r in rows]

    def verify_export(self, export_id: int) -> ExportVerification:
        rec = self.get_required(export_id)
        path = self.resolve_path(rec)
        actual: str | None = None
        sidecar_ok: bool | None = None
        if not path.is_file():
            ok = False
            msg = f"Export file not found: {path}"
        else:
            actual = sha256_file(path)
            sidecar = path.with_name(path.name + ".sha256")
            if sidecar.is_file():
                first_token = sidecar.read_text(encoding="utf-8").strip().split()[0:1]
                sidecar_ok = bool(first_token and first_token[0].lower() == rec.sha256.lower())
            if actual != rec.sha256:
                ok = False
                msg = (
                    f"SHA-256 MISMATCH for {path.name}: expected {rec.sha256[:16]}…, "
                    f"got {actual[:16]}…."
                )
            elif sidecar_ok is False:
                ok = False
                msg = f"File SHA-256 matches database, but {sidecar.name} sidecar does NOT match!"
            else:
                ok = True
                sc_note = " (and .sha256 sidecar matched)" if sidecar_ok else ""
                msg = f"Export verified OK: {path.name} SHA-256 matched{sc_note}."

        author = (self.actor() or "Analyst").strip() or "Analyst"
        with self.db.transaction() as con:
            append_event(
                con,
                "export_verified",
                case_id=rec.case_id,
                evidence_id=rec.evidence_id,
                actor_label=author,
                details={"export_id": rec.id, "ok": ok, "filename": rec.filename},
            )
        return ExportVerification(
            export_id=rec.id,
            ok=ok,
            path=path,
            expected_sha256=rec.sha256,
            actual_sha256=actual,
            sidecar_ok=sidecar_ok,
            message=msg,
        )
