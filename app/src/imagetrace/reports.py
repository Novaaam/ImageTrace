_PDF_FONTS_CACHE: tuple[str, str, str] | None = None


def _pdf_fonts() -> tuple[str, str, str]:
    """Return ``(regular, bold, mono)`` ReportLab font names.

    Attempts to register Windows TrueType Arial / Courier New so non-Latin Unicode OCR/notes
    render cleanly; falls back transparently to standard PDF Helvetica / Courier if unavailable.
    """
    global _PDF_FONTS_CACHE
    if _PDF_FONTS_CACHE is not None:
        return _PDF_FONTS_CACHE
    fonts_dir = Path(os.environ.get("WINDIR", r"C:\Windows")) / "Fonts"
    reg_p = fonts_dir / "arial.ttf"
    bold_p = fonts_dir / "arialbd.ttf"
    mono_p = fonts_dir / "cour.ttf"
    reg, bold, mono = "Helvetica", "Helvetica-Bold", "Courier"
    try:
        if reg_p.is_file() and bold_p.is_file():
            if "IT-Sans" not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(TTFont("IT-Sans", str(reg_p)))
            if "IT-Sans-Bold" not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(TTFont("IT-Sans-Bold", str(bold_p)))
            reg, bold = "IT-Sans", "IT-Sans-Bold"
        if mono_p.is_file():
            if "IT-Mono" not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(TTFont("IT-Mono", str(mono_p)))
            mono = "IT-Mono"
    except Exception:  # font registration fallback must never block export
        reg, bold, mono = "Helvetica", "Helvetica-Bold", "Courier"
    _PDF_FONTS_CACHE = (reg, bold, mono)
    return _PDF_FONTS_CACHE


