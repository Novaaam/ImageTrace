def _scaled_rl_image(raw_bytes: bytes, max_w_mm: float, max_h_mm: float) -> RlImage | None:
    """Safely re-encode bytes as RGB PNG via Pillow and return a scaled ReportLab Image."""
    with _PIL_LOCK:
        try:
            with PilImage.open(io.BytesIO(raw_bytes)) as im:
                rgb = im.convert("RGB")
                w_px, h_px = rgb.size
                if w_px <= 0 or h_px <= 0:
                    return None
                rgb.thumbnail((640, 480), PilImage.Resampling.LANCZOS)
                w_px, h_px = rgb.size
                buf = io.BytesIO()
                rgb.save(buf, format="PNG")
                buf.seek(0)
        except Exception:
            return None
    scale = min(max_w_mm / w_px, max_h_mm / h_px)
    return RlImage(buf, width=w_px * scale * mm, height=h_px * scale * mm)


def render_pdf_report(
    payload: dict[str, Any],
    dest_path: Path,
    *,
    visual_assets: dict[str, dict[str, bytes]] | None = None,
) -> None:
    """Render a validated report payload into an offline PDF using ReportLab Platypus."""
    problems = validate_report_payload(payload)
    if problems:
        raise ReportValidationError("Report payload invalid: " + "; ".join(problems))

    styles = _build_pdf_styles()
    story: list[Any] = []
    case = payload["case"]
    gen_at = payload["generated_at"]
    app_ver = payload["app_version"]
    footer_text = f"{app_ver} · Case {case['id']} · Generated {gen_at}"

    def _draw_footer(canvas: Any, doc: Any) -> None:
        canvas.saveState()
        canvas.setFont(_pdf_fonts()[0], 7.5)
