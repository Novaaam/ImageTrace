# --- pure formatting & escaping helpers ---------------------------------------------------
def _sanitize(text: Any) -> str:
    s = "" if text is None else str(text)
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    return _CONTROL_STRIP.sub("", s)


def _xml_safe(text: Any) -> str:
    """Escape text for ReportLab Paragraph mini-XML so untrusted input cannot inject markup."""
    return xml_escape(_sanitize(text)).replace("\n", "<br/>")


def _format_dms_axis(value: float, pos: str, neg: str) -> str:
    hemi = pos if value >= 0 else neg
    a = abs(value)
    deg = int(a)
    rem = (a - deg) * 60.0
    mins = int(rem)
    secs = (rem - mins) * 60.0
    return f"{deg}° {mins:02d}' {secs:05.2f}\" {hemi}"


def _format_dms_pair(lat: float, lon: float) -> str:
    return f"{_format_dms_axis(lat, 'N', 'S')}, {_format_dms_axis(lon, 'E', 'W')}"


def _check_original_integrity(ev: Evidence, orig_path: Path) -> dict[str, Any]:
    if not orig_path.is_file():
        return {
            "status": "missing",
            "expected_sha256": ev.sha256,
            "actual_sha256": None,
            "message": "Stored original file is missing on disk.",
        }
    actual = sha256_file(orig_path)
    if actual == ev.sha256:
        return {
            "status": "matched",
            "expected_sha256": ev.sha256,
            "actual_sha256": actual,
            "message": "Original file SHA-256 verified unchanged at report generation time.",
        }
    return {
        "status": "mismatch",
        "expected_sha256": ev.sha256,
        "actual_sha256": actual,
        "message": "WARNING: Stored original file SHA-256 does NOT match the import hash!",
    }


