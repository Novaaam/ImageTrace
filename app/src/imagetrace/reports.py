# --- ReportService ------------------------------------------------------------------------
class ReportService:
    def __init__(
        self,
        db: Database,
        data_root: Path,
        cases_repo: CaseRepository,
        evidence_repo: EvidenceRepository,
        metadata_service: MetadataService,
        gps_service: GpsService,
        ocr_service: OcrService,
        notes_repo: NotesRepository,
        actor: Callable[[], str] = lambda: "Analyst",
        *,
        provenance_service: ProvenanceService | None = None,
    ) -> None:
        self.db = db
        self.data_root = Path(data_root)
        self.cases = cases_repo
        self.evidence = evidence_repo
        self.metadata = metadata_service
        self.gps = gps_service
        self.ocr = ocr_service
        self.notes = notes_repo
        self.provenance = provenance_service
        self.actor = actor

    def reports_dir(self, case_id: str) -> Path:
        folder = case_dir(self.data_root / "cases", case_id) / "reports"
        folder.mkdir(parents=True, exist_ok=True)
        return folder

    def resolve_path(self, record: ExportRecord) -> Path:
        p = Path(record.path)
        if p.is_absolute():
            return p
        return (self.data_root / p).resolve()

    def _stored_path_value(self, target: Path) -> str:
        resolved = target.resolve()
        root = self.data_root.resolve()
        try:
            rel = resolved.relative_to(root)
            return rel.as_posix()
        except ValueError:
            return str(resolved)

    def _check_export_storage(self, target: Path) -> None:
        status = check_storage(self.data_root)
        if not status.available:
            raise ReportError(status.message or f"Data root unavailable: {self.data_root}")
        target_parent = target.parent
        if not target_parent.is_dir():
            raise ReportError(f"Destination folder does not exist: {target_parent}")
        free = shutil.disk_usage(target_parent).free
        if free < MIN_EXPORT_FREE_BYTES:
            raise ReportError(
                f"Insufficient free space at {target_parent} ({format_bytes(free)} free; "
                f"at least {format_bytes(MIN_EXPORT_FREE_BYTES)} required)."
            )

    def build_payload(
        self,
        case_id: str,
        *,
        evidence_id: str | None = None,
        options: ReportOptions | None = None,
        include_reportlab_tool: bool = False,
    ) -> dict[str, Any]:
        opts = options or ReportOptions()
        case: Case = self.cases.get_required(case_id)
        if evidence_id is not None:
            item = self.evidence.get_required(evidence_id)
            if item.case_id != case.id:
                raise ValidationError("Evidence item does not belong to the specified case.")
            items = [item]
            scope_desc = f"Single evidence item {item.id} ({item.original_filename})"
        else:
            items = self.evidence.list_for_case(case.id)
            scope_desc = f"Entire case {case.id} ({len(items)} evidence item(s))"

        tools_seen: dict[tuple[str, str], str] = {
            (APP_NAME, __version__): "Desktop application",
            ("Pillow", pillow_version()): "Image decoding, properties, thumbnails and dHash",
        }
        if include_reportlab_tool:
            tools_seen[("ReportLab", reportlab_version())] = "Offline PDF generation"

        evidence_entries: list[dict[str, Any]] = []
        for ev in items:
            orig_path = self.evidence.original_path(ev)
            integrity = _check_original_integrity(ev, orig_path)

            # Metadata
            meta_run, meta_records = self.metadata.latest_metadata(ev.id)
            if meta_run is None:
                meta_block: dict[str, Any] = {"has_run": False}
            else:
                src_tool = str(meta_run.output.get("source_tool", "ExifTool"))
                src_ver = str(meta_run.output.get("source_version", ""))
                if src_ver:
                    tools_seen.setdefault((src_tool, src_ver), "Metadata extraction")
                counts = {"embedded": 0, "file_container": 0, "application_system": 0}
                emb_rows: list[dict[str, str]] = []
                for r in meta_records:
                    counts[r.origin] = counts.get(r.origin, 0) + 1
                    if opts.include_full_metadata and r.origin == "embedded":
                        emb_rows.append(
                            {
                                "group": r.group_name,
                                "category": r.category,
                                "field": r.field_name,
                                "raw_value": _sanitize(r.raw_value),
                                "normalized_value": _sanitize(r.normalized_value),
                            }
                        )
                meta_block = {
                    "has_run": True,
                    "classification": "Extracted fact (embedded metadata can be edited/forged)",
                    "source_tool": src_tool,
                    "source_version": src_ver,
                    "extracted_at": meta_run.finished_at,
                    "status": meta_run.status,
                    "counts_by_origin": counts,
                    "highlights": meta_run.output.get("summary", {}),
                    "warnings": list(meta_run.warnings),
                }
                if opts.include_full_metadata:
                    meta_block["embedded_records"] = emb_rows

            # Origin & Trace (included when analyzed)
            prov_rep = self.provenance.latest_report(ev.id) if self.provenance is not None else None
            if prov_rep is not None:
                tools_seen.setdefault(
                    ("ImageTrace Origin & Trace", prov_rep.engine_version),
                    "Device/software provenance, XMP history & binary forensics",
                )

            # GPS (only included when GPS data exists, per blueprint §6!)
            _gps_run, gps_rec = self.gps.latest_state(ev.id)
            if gps_rec is not None:
                tools_seen.setdefault(
                    ("ImageTrace GPS Parser", gps_rec.parser_version),
                    "Embedded GPS parsing & validation",
                )

            # OCR
            ocr_run, ocr_items = self.ocr.latest_ocr(ev.id)
            if ocr_run is None:
                ocr_block: dict[str, Any] = {"has_run": False}
            else:
                tools_seen.setdefault((ocr_run.engine, ocr_run.engine_version), "Offline OCR")
                confs = [it.confidence for it in ocr_items if it.confidence is not None]
                mean_conf = round(sum(confs) / len(confs), 1) if confs else None
                ocr_block = {
                    "has_run": True,
                    "classification": "Automated result (untrusted machine-generated text)",
                    "engine": ocr_run.engine,
                    "engine_version": ocr_run.engine_version,
                    "language": ocr_run.language,
                    "run_at": ocr_run.run_at,
                    "status": ocr_run.status,
                    "item_count": len(ocr_items),
                    "mean_confidence": mean_conf,
                    "warnings": list(ocr_run.warnings),
                    "caveat": OCR_DISCLAIMER,
                    "full_text_included": opts.include_ocr_text,
                }
                if opts.include_ocr_text:
                    ocr_block["full_text_untrusted"] = _sanitize(ocr_run.full_text)

            # Notes
            ev_notes = self.notes.list_for_evidence(
                ev.id, include_history=opts.include_note_history
            )
            entry: dict[str, Any] = {
                "id": ev.id,
                "original_filename": _sanitize(ev.original_filename),
                "stored_filename": ev.stored_filename,
                "file_size": ev.file_size,
                "detected_format": ev.detected_format,
                "detected_mime": ev.detected_mime,
                "sha256": ev.sha256,
                "integrity_check": integrity,
                "imported_at": ev.imported_at,
                "imported_at_timezone": "UTC",
                "import_source_note": _sanitize(ev.import_source_note),
                "status": ev.status,
                "warnings": list(ev.warnings),
                "image_properties": {
                    "classification": "Extracted fact (deterministic file byte analysis)",
                    "width": ev.width,
                    "height": ev.height,
                    "color_mode": ev.color_mode,
                    "icc_profile_info": ev.icc_profile_info,
                    "dhash": ev.dhash,
                    "dhash_caveat": (
                        "64-bit dHash is an automated similarity heuristic, not proof of identity."
                    ),
                },
                "metadata": meta_block,
                "ocr": ocr_block,
                "notes": [_serialize_note(n) for n in ev_notes],
            }
            if prov_rep is not None:
                entry["origin_trace"] = prov_rep.to_dict()
            if gps_rec is not None:
                entry["gps"] = _serialize_gps(gps_rec)
            evidence_entries.append(entry)

        # Case-level notes (notes with evidence_id IS NULL)
        case_notes = [
            _serialize_note(n)
            for n in self.notes.list_for_case(case.id, include_history=opts.include_note_history)
            if n.evidence_id is None
        ]

        # Audit history summary (sanitized: event_type, timestamp, actor, evidence_id)
        chain = verify_chain(self.db.con)
        raw_events = (
            list_events(self.db.con, evidence_id=evidence_id)
            if evidence_id is not None
            else list_events(self.db.con, case_id=case.id)
        )
        serialized_events = [
            {
                "id": e.id,
                "event_time": e.event_time,
                "event_type": e.event_type,
                "label": _EVENT_LABELS.get(e.event_type, e.event_type),
                "actor_label": _sanitize(e.actor_label),
                "evidence_id": e.evidence_id,
            }
            for e in raw_events
        ]

        payload: dict[str, Any] = {
            "report_schema_version": REPORT_SCHEMA_VERSION,
            "generated_at": utc_now_iso(),
            "generated_at_timezone": "UTC",
            "app_version": f"{APP_NAME} {__version__}",
            "generated_by": _sanitize((self.actor() or "Analyst").strip() or "Analyst"),
            "scope_description": scope_desc,
            "options": opts.to_dict(),
            "legend": dict(REPORT_LEGEND),
            "limitations": list(REPORT_LIMITATIONS),
            "tools": [
                {"name": name, "version": ver, "role": role}
                for (name, ver), role in tools_seen.items()
            ],
            "case": {
                "id": case.id,
                "title": _sanitize(case.title),
                "status": case.status,
                "tags": list(case.tags),
                "scope_text": _sanitize(case.scope_text),
                "notes": _sanitize(case.notes),
                "created_at": case.created_at,
                "updated_at": case.updated_at,
            },
            "case_notes": case_notes,
            "evidence": evidence_entries,
            "audit_summary": {
                "chain_ok": chain.ok,
                "chain_checked_events": chain.checked,
                "chain_message": chain.message,
                "events": serialized_events,
            },
        }
        return payload

    def _default_filename(self, case_id: str, evidence_id: str | None, ext: str) -> str:
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
        target = evidence_id or case_id
        return f"ImageTrace-{target}-{stamp}.{ext}"

    def _unique_default_path(self, case_id: str, evidence_id: str | None, ext: str) -> Path:
        rdir = self.reports_dir(case_id)
        base = self._default_filename(case_id, evidence_id, ext)
        target = rdir / base
        if not target.exists():
            return target
        stem = Path(base).stem
        n = 2
        while target.exists():
            target = rdir / f"{stem}-{n}.{ext}"
            n += 1
        return target

    def _export(
        self,
        case_id: str,
        *,
        export_type: str,
        evidence_id: str | None = None,
        dest_path: Path | None = None,
        options: ReportOptions | None = None,
    ) -> ExportRecord:
        if export_type not in EXPORT_TYPES:
            raise ValidationError(f"Unsupported export type: {export_type!r}")
        opts = options or ReportOptions()
        is_pdf = export_type == "pdf_report"
        payload = self.build_payload(
            case_id,
            evidence_id=evidence_id,
            options=opts,
            include_reportlab_tool=is_pdf,
        )
        problems = validate_report_payload(payload)
        if problems:
            raise ReportValidationError("Report validation failed: " + "; ".join(problems))

        ext = "pdf" if is_pdf else "json"
        if dest_path is None:
            target = self._unique_default_path(case_id, evidence_id, ext)
        else:
            target = Path(dest_path)
            if target.suffix.lower() != f".{ext}":
                target = target.with_suffix(f".{ext}")
        self._check_export_storage(target)

        partial = target.with_name(target.name + ".partial")
        try:
            if is_pdf:
                vis_assets: dict[str, dict[str, bytes]] = {}
                if opts.include_visuals:
                    for ev_entry in payload["evidence"]:
                        ev_obj = self.evidence.get(ev_entry["id"])
                        if ev_obj is None:
                            continue
                        asset: dict[str, bytes] = {}
                        t_path = self.evidence.thumbnail_path(ev_obj)
                        if t_path is not None and t_path.is_file():
                            asset["main"] = t_path.read_bytes()
                        if ((ev_entry.get("origin_trace") or {}).get("thumbnail_check") or {}).get(
                            "status"
                        ) == "mismatch":
                            orig_p = self.evidence.original_path(ev_obj)
                            et_bytes = extract_embedded_thumbnail_bytes(orig_p)
                            if et_bytes:
                                asset["exif_thumb"] = et_bytes
                        if asset:
                            vis_assets[ev_obj.id] = asset
                render_pdf_report(payload, partial, visual_assets=vis_assets or None)
                head = partial.read_bytes()[:5]
                if head != b"%PDF-":
                    raise ReportError("Generated PDF did not start with a valid %PDF- header.")
            else:
                encoded = (json.dumps(payload, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
                partial.write_bytes(encoded)
                # Verify round-trip parseability before publishing
                json.loads(partial.read_text(encoding="utf-8"))
            os.replace(partial, target)
        except BaseException:
            partial.unlink(missing_ok=True)
            raise

        digest = sha256_file(target)
        sidecar = target.with_name(target.name + ".sha256")
        sidecar.write_text(f"{digest}  {target.name}\n", encoding="utf-8")

        author = (self.actor() or "Analyst").strip() or "Analyst"
        now = utc_now_iso()
        stored_path = self._stored_path_value(target)
        with self.db.transaction() as con:
            cur = con.execute(
                "INSERT INTO exports ("
                "case_id, evidence_id, export_type, path, sha256, actor_label, options_json, "
                "created_at"
                ") VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (
                    case_id,
                    evidence_id,
                    export_type,
                    stored_path,
                    digest,
                    author,
                    json.dumps(opts.to_dict(), sort_keys=True),
                    now,
                ),
            )
            export_id = int(cur.lastrowid)
            append_event(
                con,
                "report_exported",
                case_id=case_id,
                evidence_id=evidence_id,
                actor_label=author,
                details={
                    "export_id": export_id,
                    "export_type": export_type,
                    "filename": target.name,
                    "sha256": digest,
                    "evidence_count": len(payload["evidence"]),
                    "include_ocr_text": opts.include_ocr_text,
                },
            )
        log.info(
            "Report exported: #%d (%s, case=%s, sha256=%s...)",
            export_id,
            export_type,
            case_id,
            digest[:12],
        )
        return self.get_required(export_id)

